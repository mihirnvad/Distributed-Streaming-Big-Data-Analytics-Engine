    credit_limit_usd   numeric(12, 2),
    has_chip_card      boolean
);

-- Applies staging.users to dw.dim_users as SCD Type 2 and returns (inserted, expired).
CREATE OR REPLACE FUNCTION dw.merge_dim_users(p_effective_at timestamptz DEFAULT now())
RETURNS TABLE (inserted_rows bigint, expired_rows bigint)
LANGUAGE plpgsql AS $$
DECLARE
    v_expired  bigint;
    v_inserted bigint;
BEGIN
    CREATE TEMP TABLE _incoming ON COMMIT DROP AS
    SELECT s.*,
           l.location_key,
           l.latitude  AS home_lat,
           l.longitude AS home_lon,
           -- Tracked (type-2) attributes only; account_open_date is immutable and kept from the first load.
           md5(concat_ws('|', s.card_id, s.home_city, s.home_country_code, s.card_network, s.card_tier,
                         s.segment, s.credit_limit_usd, s.has_chip_card)) AS row_hash
    FROM staging.users s
    JOIN dw.dim_location l ON l.city = s.home_city AND l.country_code = s.home_country_code;

    -- Close out current versions whose tracked attributes changed.
    UPDATE dw.dim_users d
       SET valid_to = p_effective_at, is_current = false
      FROM _incoming i
     WHERE d.user_id = i.user_id AND d.is_current AND d.row_hash <> i.row_hash;
    GET DIAGNOSTICS v_expired = ROW_COUNT;

    -- Insert brand-new users and new versions of changed users.
    INSERT INTO dw.dim_users (user_id, card_id, home_location_key, home_city, home_country_code, home_lat,
                              home_lon, card_network, card_tier, segment, account_open_date, credit_limit_usd,
                              has_chip_card, row_hash, valid_from)
    SELECT i.user_id, i.card_id, i.location_key, i.home_city, i.home_country_code, i.home_lat, i.home_lon,
           i.card_network, i.card_tier, i.segment, i.account_open_date, i.credit_limit_usd, i.has_chip_card,
           i.row_hash, p_effective_at
      FROM _incoming i
     WHERE NOT EXISTS (SELECT 1 FROM dw.dim_users d WHERE d.user_id = i.user_id AND d.is_current);
    GET DIAGNOSTICS v_inserted = ROW_COUNT;

    RETURN QUERY SELECT v_inserted, v_expired;
END $$;

