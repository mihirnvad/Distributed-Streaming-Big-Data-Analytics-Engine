-- Great-circle distance in km (matches common/geo.py).
CREATE OR REPLACE FUNCTION dw.haversine_km(
    lat1 double precision, lon1 double precision,
    lat2 double precision, lon2 double precision
) RETURNS double precision
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT AS $$
    SELECT 2 * 6371.0088 * asin(least(1.0, sqrt(
        power(sin(radians(lat2 - lat1) / 2), 2)
        + cos(radians(lat1)) * cos(radians(lat2)) * power(sin(radians(lon2 - lon1) / 2), 2)
    )))
$$;

CREATE OR REPLACE FUNCTION dw.to_date_key(ts timestamptz)
RETURNS integer LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT AS $$
    SELECT (to_char(ts AT TIME ZONE 'UTC', 'YYYYMMDD'))::integer
$$;

