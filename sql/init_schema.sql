    transaction_id          uuid           NOT NULL,          -- degenerate dimension
    event_ts                timestamptz    NOT NULL,
    date_key                integer        NOT NULL,
    user_key                bigint         NOT NULL,
    merchant_key            bigint         NOT NULL,
    location_key            integer        NOT NULL,
    amount                  numeric(14, 2) NOT NULL,
    currency_code           char(3)        NOT NULL,
    amount_usd              numeric(14, 2) NOT NULL,
    channel                 text           NOT NULL,
    entry_mode              text           NOT NULL,
    txn_lat                 double precision,
    txn_lon                 double precision,
    -- real-time features computed by the stateful streaming operator
    distance_from_home_km   real,
    km_from_prev            real,
    seconds_since_prev      real,
    implied_speed_kmh       real,
    txn_count_1m            smallint,
    txn_count_5m            smallint,
    amount_usd_5m           numeric(14, 2),
    distinct_merchants_5m   smallint,
    small_txn_count_5m      smallint,
    amount_zscore           real,
    -- rule-engine output
    fraud_score             numeric(5, 4)  NOT NULL,
    risk_level              text           NOT NULL,
    is_flagged              boolean        NOT NULL,
    reason_codes            text[]         NOT NULL DEFAULT '{}',
    -- lineage
    kafka_partition         integer,
    kafka_offset            bigint,
    kafka_ts                timestamptz,
    processed_at            timestamptz,
    loaded_at               timestamptz    NOT NULL DEFAULT now(),
    PRIMARY KEY (transaction_id, event_ts)
) PARTITION BY RANGE (event_ts);

