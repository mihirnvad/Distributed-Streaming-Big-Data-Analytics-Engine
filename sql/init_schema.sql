-- Creates missing daily partitions for [p_start, p_start + p_days). Rows that already
-- landed in the DEFAULT partition for that range are moved into the new partition.
CREATE OR REPLACE FUNCTION dw.ensure_daily_partitions(p_start date, p_days integer)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    v_day      date;
    v_lo       timestamptz;
    v_hi       timestamptz;
    v_name     text;
    v_created  integer := 0;
BEGIN
    FOR i IN 0 .. p_days - 1 LOOP
        v_day  := p_start + i;
        v_name := 'fact_transactions_' || to_char(v_day, 'YYYYMMDD');
        CONTINUE WHEN to_regclass('dw.' || v_name) IS NOT NULL;

        v_lo := v_day::timestamp AT TIME ZONE 'UTC';
        v_hi := (v_day + 1)::timestamp AT TIME ZONE 'UTC';

        IF EXISTS (SELECT 1 FROM dw.fact_transactions_default WHERE event_ts >= v_lo AND event_ts < v_hi) THEN
            -- Postgres refuses to attach a range the DEFAULT partition already holds rows for,
            -- so park those rows, create the partition, then re-insert (routes to the new one).
            CREATE TEMP TABLE IF NOT EXISTS _default_rows (LIKE dw.fact_transactions) ON COMMIT DROP;
            TRUNCATE _default_rows;
            INSERT INTO _default_rows
                SELECT * FROM dw.fact_transactions_default WHERE event_ts >= v_lo AND event_ts < v_hi;
            DELETE FROM dw.fact_transactions_default WHERE event_ts >= v_lo AND event_ts < v_hi;
            EXECUTE format('CREATE TABLE dw.%I PARTITION OF dw.fact_transactions FOR VALUES FROM (%L) TO (%L)',
                           v_name, v_lo, v_hi);
            INSERT INTO dw.fact_transactions SELECT * FROM _default_rows;
        ELSE
            EXECUTE format('CREATE TABLE dw.%I PARTITION OF dw.fact_transactions FOR VALUES FROM (%L) TO (%L)',
                           v_name, v_lo, v_hi);
        END IF;
        v_created := v_created + 1;
    END LOOP;
    RETURN v_created;
END $$;

SELECT dw.ensure_daily_partitions(current_date - 7, 45);

-- Grain: one row per transaction the rule engine flagged. Carries case status,
-- which is resolved by chargebacks (confirmed) or label maturity (false positive).
CREATE TABLE IF NOT EXISTS dw.fact_fraud_alerts (
    alert_id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    transaction_id      uuid           NOT NULL UNIQUE,
    event_ts            timestamptz    NOT NULL,
    date_key            integer        NOT NULL,
    user_key            bigint         NOT NULL,
    merchant_key        bigint         NOT NULL,
    amount_usd          numeric(14, 2) NOT NULL,
    fraud_score         numeric(5, 4)  NOT NULL,
    risk_level          text           NOT NULL,
    reason_codes        text[]         NOT NULL,
    status              text           NOT NULL DEFAULT 'OPEN'
                        CHECK (status IN ('OPEN', 'CONFIRMED_FRAUD', 'FALSE_POSITIVE')),
    status_updated_at   timestamptz,
    created_at          timestamptz    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_alerts_created_at ON dw.fact_fraud_alerts (created_at DESC);
CREATE INDEX IF NOT EXISTS ix_alerts_event_ts ON dw.fact_fraud_alerts (event_ts DESC);
CREATE INDEX IF NOT EXISTS ix_alerts_status ON dw.fact_fraud_alerts (status) WHERE status = 'OPEN';

