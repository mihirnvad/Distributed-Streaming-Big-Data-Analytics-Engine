CREATE OR REPLACE VIEW dw.v_transactions_enriched AS
SELECT f.transaction_id,
       f.event_ts,
       d.full_date,
       d.is_weekend,
       u.user_id,
       u.segment,
       u.card_tier,
       u.card_network,
       u.home_city,
       m.merchant_id,
       m.merchant_name,
       m.is_online,
       c.mcc,
       c.category_name,
       c.risk_tier AS category_risk_tier,
       l.city      AS txn_city,
       l.country_code AS txn_country,
       f.amount,
       f.currency_code,
       f.amount_usd,
       f.channel,
       f.entry_mode,
       f.distance_from_home_km,
       f.implied_speed_kmh,
       f.txn_count_5m,
       f.amount_zscore,
       f.fraud_score,
       f.risk_level,
       f.is_flagged,
       f.reason_codes,
       f.loaded_at
FROM dw.fact_transactions f
JOIN dw.dim_date d              ON d.date_key = f.date_key
JOIN dw.dim_users u             ON u.user_key = f.user_key
JOIN dw.dim_merchants m         ON m.merchant_key = f.merchant_key
JOIN dw.dim_merchant_category c ON c.mcc = m.mcc
JOIN dw.dim_location l          ON l.location_key = f.location_key;

